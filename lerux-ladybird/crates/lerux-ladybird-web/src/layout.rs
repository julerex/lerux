//! Block and line boxes for one styled document.
//!
//! A layout box is a block, an anonymous block, or a line. It is not a DOM
//! node. `display: none` generates no box. The initial containing block is
//! the frame. A block lays its block children out in order. The first child's
//! top margin stays inside the parent, so the body margin and the paragraph
//! margin add. Adjoining sibling margins keep the larger one.
//!
//! Inline children become line boxes. Glyph advance and line height are the
//! frame font cell, not the computed `font-size`. A line keeps the color of
//! the element that generated it, so an inline color survives the flattening.
//! A block that also has a block child wraps each inline run in an anonymous
//! block. The block keeps its computed style for paint.
//!
//! Floats, flex, grid, tables, and absolute positioning are out of scope.

use alloc::vec::Vec;
use core::{
    fmt::{self, Debug, Formatter},
    mem::take,
};

use lerux_ladybird_gfx::{Rect, FRAME_HEIGHT, FRAME_WIDTH, GLYPH_HEIGHT, GLYPH_WIDTH};
use lerux_ladybird_html::Element;

use crate::style::{
    Color, ComputedStyle, Display, Edges, StyledDocument, StyledElement, StyledNode, Width,
};

/// The box tree for one styled document.
///
/// The root is the initial containing block, sized to the frame. Its children
/// are the boxes generated by the document.
pub struct LayoutTree<'s, 'd> {
    frame: Rect,
    children: Vec<LayoutBox<'s, 'd>>,
}

impl<'s, 'd> LayoutTree<'s, 'd> {
    /// The initial containing block.
    #[must_use]
    pub fn frame(&self) -> Rect {
        self.frame
    }

    #[must_use]
    pub fn children(&self) -> &[LayoutBox<'s, 'd>] {
        &self.children
    }
}

impl<'d> StyledDocument<'d> {
    /// Lay this document out in the frame.
    #[must_use]
    pub fn layout(&self) -> LayoutTree<'_, 'd> {
        let width = as_i32(FRAME_WIDTH);
        let height = as_i32(FRAME_HEIGHT);
        let (children, _) = layout_contents(self.children(), 0, 0, width, Color::BLACK);
        LayoutTree {
            frame: Rect::new(0, 0, width, height),
            children,
        }
    }
}

/// A block, an anonymous block, or a line.
#[derive(Debug)]
pub enum LayoutBox<'s, 'd> {
    Block(BlockBox<'s, 'd>),
    Anonymous(AnonymousBox<'s, 'd>),
    Line(LineBox<'d>),
}

/// A box generated by an element.
pub struct BlockBox<'s, 'd> {
    element: &'s Element<'d>,
    style: &'s ComputedStyle,
    rect: Rect,
    children: Vec<LayoutBox<'s, 'd>>,
}

impl<'s, 'd> BlockBox<'s, 'd> {
    #[must_use]
    pub fn element(&self) -> &'s Element<'d> {
        self.element
    }

    #[must_use]
    pub(crate) fn style(&self) -> &'s ComputedStyle {
        self.style
    }

    #[must_use]
    pub fn rect(&self) -> Rect {
        self.rect
    }

    #[must_use]
    pub fn children(&self) -> &[LayoutBox<'s, 'd>] {
        &self.children
    }
}

impl Debug for BlockBox<'_, '_> {
    fn fmt(&self, f: &mut Formatter<'_>) -> fmt::Result {
        f.debug_struct("BlockBox")
            .field("element", &self.element.name())
            .field("rect", &self.rect)
            .field("children", &self.children)
            .finish()
    }
}

/// An inline run wrapped because a block sibling shares its parent.
#[derive(Debug)]
pub struct AnonymousBox<'s, 'd> {
    rect: Rect,
    children: Vec<LayoutBox<'s, 'd>>,
}

impl<'s, 'd> AnonymousBox<'s, 'd> {
    #[must_use]
    pub fn rect(&self) -> Rect {
        self.rect
    }

    #[must_use]
    pub fn children(&self) -> &[LayoutBox<'s, 'd>] {
        &self.children
    }
}

/// One line of glyphs.
#[derive(Debug)]
pub struct LineBox<'d> {
    text: &'d str,
    rect: Rect,
    color: Color,
}

impl<'d> LineBox<'d> {
    #[must_use]
    pub fn text(&self) -> &'d str {
        self.text
    }

    #[must_use]
    pub fn rect(&self) -> Rect {
        self.rect
    }

    #[must_use]
    pub fn color(&self) -> Color {
        self.color
    }
}

#[derive(Clone, Copy)]
struct ColoredText<'d> {
    text: &'d str,
    color: Color,
}

enum Piece<'s, 'd> {
    Text(ColoredText<'d>),
    Block(&'s StyledElement<'d>),
}

impl Piece<'_, '_> {
    fn is_block(&self) -> bool {
        matches!(self, Self::Block(_))
    }
}

enum Flow<'s, 'd> {
    Inlines(Vec<ColoredText<'d>>),
    Block(&'s StyledElement<'d>),
}

struct Placed<'s, 'd> {
    layout: LayoutBox<'s, 'd>,
    margin_bottom: i32,
}

fn layout_contents<'s, 'd>(
    nodes: &'s [StyledNode<'d>],
    content_x: i32,
    content_y: i32,
    content_width: i32,
    color: Color,
) -> (Vec<LayoutBox<'s, 'd>>, i32) {
    let pieces = pieces(nodes, color);
    if pieces.iter().any(Piece::is_block) {
        place_blocks(&block_flows(&pieces), content_x, content_y, content_width)
    } else {
        layout_lines(&inline_texts(&pieces), content_x, content_y)
    }
}

fn pieces<'s, 'd>(nodes: &'s [StyledNode<'d>], color: Color) -> Vec<Piece<'s, 'd>> {
    let mut pieces = Vec::new();
    collect_pieces(nodes, &mut pieces, color);
    pieces
}

fn collect_pieces<'s, 'd>(
    nodes: &'s [StyledNode<'d>],
    pieces: &mut Vec<Piece<'s, 'd>>,
    color: Color,
) {
    for node in nodes {
        match node {
            StyledNode::Text(text) => pieces.push(Piece::Text(ColoredText {
                text: text.data(),
                color,
            })),
            StyledNode::Element(element) => push_element(element, pieces),
        }
    }
}

fn push_element<'s, 'd>(element: &'s StyledElement<'d>, pieces: &mut Vec<Piece<'s, 'd>>) {
    match element.style().display() {
        Display::None => {}
        Display::Block => pieces.push(Piece::Block(element)),
        Display::Inline => collect_pieces(element.children(), pieces, element.style().color()),
    }
}

fn inline_texts<'d>(pieces: &[Piece<'_, 'd>]) -> Vec<ColoredText<'d>> {
    pieces
        .iter()
        .filter_map(|piece| match piece {
            Piece::Text(text) if !text.text.is_empty() => Some(*text),
            Piece::Text(_) | Piece::Block(_) => None,
        })
        .collect()
}

fn block_flows<'s, 'd>(pieces: &[Piece<'s, 'd>]) -> Vec<Flow<'s, 'd>> {
    let mut flows = Vec::new();
    let mut run = Vec::new();
    for piece in pieces {
        match piece {
            Piece::Text(text) => keep_text(text, &mut run),
            Piece::Block(element) => {
                flush_run(&mut run, &mut flows);
                flows.push(Flow::Block(element));
            }
        }
    }
    flush_run(&mut run, &mut flows);
    flows
}

fn keep_text<'d>(text: &ColoredText<'d>, run: &mut Vec<ColoredText<'d>>) {
    if !text.text.is_empty() {
        run.push(*text);
    }
}

fn flush_run<'d>(run: &mut Vec<ColoredText<'d>>, flows: &mut Vec<Flow<'_, 'd>>) {
    if run.is_empty() {
        return;
    }
    flows.push(Flow::Inlines(take(run)));
}

fn place_blocks<'s, 'd>(
    flows: &[Flow<'s, 'd>],
    content_x: i32,
    content_y: i32,
    content_width: i32,
) -> (Vec<LayoutBox<'s, 'd>>, i32) {
    let mut children = Vec::new();
    let mut border_bottom = content_y;
    let mut previous_margin = None;
    for flow in flows {
        let border_y = border_bottom + collapse(previous_margin, margin_top(flow));
        let placed = place_flow(flow, content_x, border_y, content_width);
        border_bottom = bottom(&placed.layout);
        previous_margin = Some(placed.margin_bottom);
        children.push(placed.layout);
    }
    let height = content_height(content_y, border_bottom, previous_margin);
    (children, height)
}

/// The parent keeps its own margin. The first child keeps its top margin.
/// The next sibling keeps the larger of the two adjoining margins.
fn collapse(previous_margin: Option<i32>, top: i32) -> i32 {
    match previous_margin {
        None => top,
        Some(bottom) => bottom.max(top),
    }
}

fn content_height(content_y: i32, border_bottom: i32, last_margin: Option<i32>) -> i32 {
    match last_margin {
        None => 0,
        Some(margin) => border_bottom + margin - content_y,
    }
}

fn margin_top(flow: &Flow<'_, '_>) -> i32 {
    match flow {
        Flow::Inlines(_) => 0,
        Flow::Block(element) => element.style().margin().top,
    }
}

fn place_flow<'s, 'd>(
    flow: &Flow<'s, 'd>,
    content_x: i32,
    border_y: i32,
    content_width: i32,
) -> Placed<'s, 'd> {
    match flow {
        Flow::Inlines(texts) => place_anonymous(texts, content_x, border_y, content_width),
        Flow::Block(element) => place_block(element, content_x, border_y, content_width),
    }
}

fn place_block<'s, 'd>(
    element: &'s StyledElement<'d>,
    content_x: i32,
    border_y: i32,
    containing_width: i32,
) -> Placed<'s, 'd> {
    let border_x = content_x + element.style().margin().left;
    let block = layout_block(element, border_x, border_y, containing_width);
    Placed {
        margin_bottom: element.style().margin().bottom,
        layout: LayoutBox::Block(block),
    }
}

fn place_anonymous<'s, 'd>(
    texts: &[ColoredText<'d>],
    x: i32,
    y: i32,
    width: i32,
) -> Placed<'s, 'd> {
    let (children, height) = layout_lines(texts, x, y);
    Placed {
        margin_bottom: 0,
        layout: LayoutBox::Anonymous(AnonymousBox {
            rect: Rect::new(x, y, width, height),
            children,
        }),
    }
}

/// HTML's default iframe height, in CSS pixels. The frame is shorter, so paint clips it.
const IFRAME_HEIGHT: i32 = 150;

fn layout_block<'s, 'd>(
    element: &'s StyledElement<'d>,
    border_x: i32,
    border_y: i32,
    containing_width: i32,
) -> BlockBox<'s, 'd> {
    let padding = padding_px(element.style().padding());
    let content_width = content_width(element.style(), containing_width);
    let (children, mut inner) = layout_contents(
        element.children(),
        border_x + padding.left,
        border_y + padding.top,
        content_width,
        element.style().color(),
    );
    if element.element().name() == "iframe" {
        inner = inner.max(IFRAME_HEIGHT);
    }
    BlockBox {
        element: element.element(),
        style: element.style(),
        rect: Rect::new(
            border_x,
            border_y,
            content_width + padding.left + padding.right,
            padding.top + inner + padding.bottom,
        ),
        children,
    }
}

fn content_width(style: &ComputedStyle, containing_width: i32) -> i32 {
    match style.width() {
        Width::Px(px) => as_i32(px),
        Width::Auto => auto_content_width(style, containing_width),
    }
}

fn auto_content_width(style: &ComputedStyle, containing_width: i32) -> i32 {
    let margin = style.margin();
    let padding = padding_px(style.padding());
    let used = containing_width - margin.left - margin.right - padding.left - padding.right;
    used.max(0)
}

fn layout_lines<'s, 'd>(
    texts: &[ColoredText<'d>],
    x: i32,
    y: i32,
) -> (Vec<LayoutBox<'s, 'd>>, i32) {
    let mut children = Vec::new();
    let mut cursor = x;
    for text in texts {
        let width = text_width(text.text);
        children.push(LayoutBox::Line(LineBox {
            text: text.text,
            rect: Rect::new(cursor, y, width, GLYPH_HEIGHT),
            color: text.color,
        }));
        cursor += width;
    }
    let height = if children.is_empty() { 0 } else { GLYPH_HEIGHT };
    (children, height)
}

fn bottom(layout: &LayoutBox<'_, '_>) -> i32 {
    let rect = match layout {
        LayoutBox::Block(block) => block.rect(),
        LayoutBox::Anonymous(anonymous) => anonymous.rect(),
        LayoutBox::Line(line) => line.rect(),
    };
    rect.y + rect.height
}

fn padding_px(edges: Edges<u32>) -> Edges<i32> {
    Edges {
        top: as_i32(edges.top),
        right: as_i32(edges.right),
        bottom: as_i32(edges.bottom),
        left: as_i32(edges.left),
    }
}

fn text_width(text: &str) -> i32 {
    let glyphs = i32::try_from(text.chars().count()).unwrap_or(i32::MAX);
    glyphs.saturating_mul(GLYPH_WIDTH)
}

fn as_i32(value: u32) -> i32 {
    i32::try_from(value).unwrap_or(i32::MAX)
}
