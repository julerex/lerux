const fn spec(
    family: &'static [u8],
    caption: &'static [u8],
    entity: bool,
    name: &'static [u8],
    line: &'static [u8],
    desc: &'static [u8],
    id: u8,
) -> Spec {
    Spec {
        family,
        caption,
        entity,
        name,
        line,
        desc,
        id,
    }
}

pub(crate) fn find(family: &[u8], entity: bool, name: &[u8]) -> Option<&'static Spec> {
    SPECS
        .iter()
        .find(|spec| spec.family == family && spec.entity == entity && spec.name == name)
}

pub(crate) fn family_known(family: &[u8]) -> bool {
    SPECS.iter().any(|spec| spec.family == family)
}
